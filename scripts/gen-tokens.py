#!/usr/bin/env python3
import argparse
import os
import subprocess
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "design", "tokens.toml")
QML_OUT = os.path.join(ROOT, "quickshell", "island", "Tokens.js")
RUST_OUT = os.path.join(ROOT, "src", "halcyon-music", "crates", "halcyon-music-core", "src", "tokens.rs")


def num(v):
    return str(v) if isinstance(v, int) else repr(float(v))


def f32(v):
    s = repr(float(v))
    return s if "." in s or "e" in s else s + ".0"


def js_key(k):
    return k if k.replace("_", "").isalnum() and "-" not in k else f'"{k}"'


def render_qml(t):
    out = ["// @generated by scripts/gen-tokens.py from design/tokens.toml", ".pragma library", ""]
    out.append(f"var version = {t['version']}")
    for group in ("space", "radius", "type", "size"):
        body = ", ".join(f"{js_key(k)}: {num(v)}" for k, v in t[group].items())
        out.append(f"var {group} = {{ {body} }}")
    m = t["motion"]
    body = ", ".join(
        f"{k}: [{', '.join(num(x) for x in v)}]" if isinstance(v, list) else f"{k}: {num(v)}" for k, v in m.items()
    )
    out.append(f"var motion = {{ {body} }}")
    sh = ", ".join(
        f"{k}: {{ y: {num(v['y'])}, blur: {num(v['blur'])}, alpha: {num(v['alpha'])} }}" for k, v in t["shadow"].items()
    )
    out.append(f"var shadow = {{ {sh} }}")
    for scheme, colors in t["color"].items():
        body = ", ".join(f'{js_key(k)}: "{v}"' for k, v in colors.items())
        out.append(f"var {scheme} = {{ {body} }}")
    body = ", ".join(f"{js_key(k)}: 0x{v:X}" for k, v in t["icon"].items())
    out.append(f"var icon = {{ {body} }}")
    return "\n".join(out) + "\n"


def rust_name(k):
    return k.upper().replace("-", "_")


def render_rust(t):
    out = ["// @generated by scripts/gen-tokens.py from design/tokens.toml", ""]
    out.append(f"pub const VERSION: u32 = {t['version']};")
    for group, mod in (("space", "space"), ("radius", "radius"), ("type", "text"), ("size", "size")):
        out += ["", f"pub mod {mod} {{"]
        out += [f"    pub const {rust_name(k)}: f32 = {f32(v)};" for k, v in t[group].items()]
        out.append("}")
    out += ["", "pub mod motion {"]
    for k, v in t["motion"].items():
        if isinstance(v, list):
            out.append(f"    pub const {rust_name(k)}: [f32; 4] = [{', '.join(f32(x) for x in v)}];")
        else:
            out.append(f"    pub const {rust_name(k)}_MS: u64 = {v};")
    out.append("}")
    out += ["", "pub mod shadow {", "    pub struct Shadow {", "        pub y: f32,", "        pub blur: f32,", "        pub alpha: f32,", "    }"]
    for k, v in t["shadow"].items():
        out.append(
            f"    pub const {rust_name(k)}: Shadow = Shadow {{ y: {f32(v['y'])}, blur: {f32(v['blur'])}, alpha: {f32(v['alpha'])} }};"
        )
    out.append("}")
    out += ["", "pub mod color {"]
    for scheme, colors in t["color"].items():
        out.append(f"    pub mod {scheme} {{")
        out += [f"        pub const {rust_name(k)}: u32 = 0x{v.lstrip('#').lower()};" for k, v in colors.items()]
        out.append("    }")
    out.append("}")
    out += ["", "pub mod icon {"]
    out += [f"    pub const {rust_name(k)}: u32 = 0x{v:X};" for k, v in t["icon"].items()]
    out.append("}")
    text = "\n".join(out) + "\n"
    done = subprocess.run(["rustfmt", "--edition", "2021"], input=text, capture_output=True, text=True)
    return done.stdout if done.returncode == 0 and done.stdout else text


def validate(t):
    problems = []
    if list(t["space"].values()) != [4, 8, 12, 16, 24]:
        problems.append("space must be the 4/8/12/16/24 scale")
    for k in ("fast", "base", "slow", "close"):
        if not 120 <= t["motion"][k] <= 700:
            problems.append(f"motion.{k} must be within 120-700 ms")
    if t["size"]["hit_min"] < 32:
        problems.append("size.hit_min must be at least 32")
    for scheme, colors in t["color"].items():
        for k, v in colors.items():
            if not (isinstance(v, str) and len(v) == 7 and v.startswith("#")):
                problems.append(f"color.{scheme}.{k} must be #rrggbb")
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--also-rust", action="append", default=[], metavar="PATH")
    args = ap.parse_args()
    with open(SOURCE, "rb") as f:
        tokens = tomllib.load(f)
    problems = validate(tokens)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    targets = [(QML_OUT, render_qml(tokens)), (RUST_OUT, render_rust(tokens))]
    targets += [(os.path.abspath(p), render_rust(tokens)) for p in args.also_rust]
    stale = []
    for path, text in targets:
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        if args.check:
            stale.append(path)
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print(f"wrote {os.path.relpath(path, ROOT)}")
    if stale:
        print("out of date (run scripts/gen-tokens.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
